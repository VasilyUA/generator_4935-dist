def write_docx(path, paragraphs):
    """paragraphs - рядок або (текст, {"bold": [фрази], "style": "Heading 1"})."""
    doc = Document()
    for entry in paragraphs:
        text, options = (entry if isinstance(entry, tuple) else (entry, {}))
        paragraph = doc.add_paragraph(style=options.get("style"))
        remaining = text
        bold_phrases = options.get("bold", [])
        while remaining:
            positions = [(remaining.find(p), p) for p in bold_phrases if p and remaining.find(p) != -1]
            if not positions:
                paragraph.add_run(remaining)
                break
            pos, phrase = min(positions)
            if pos:
                paragraph.add_run(remaining[:pos])
            paragraph.add_run(phrase).bold = True
            remaining = remaining[pos + len(phrase):]
    doc.save(path)
    return path


