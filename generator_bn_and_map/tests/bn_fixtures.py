def tiny_png(path):
    """PNG 1x1 - для синтетичного "зразка" з малюнком."""
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
    signature = bytes([0x89]) + b"PNG" + bytes([13, 10, 26, 10])
    png = signature + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 2, 0, 0, 0))         + chunk(b"IDAT", zlib.compress(bytes([0, 255, 255, 255]))) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)
    return path


def write_style_reference(path, png_path):
    """Синтетичний "зразок" БН: титул з малюнком, заголовок, два однаково
    відформатовані абзаци, порожній абзац з розривом сторінки, рядок підпису й
    таблиця (заголовок на всю ширину, шапка, рядок даних, порожній рядок).
    Індекси елементів тіла: 0 титул, 1 заголовок, 2-3 текст, 4 розрив, 5 підпис, 6 таблиця."""
    doc = Document()
    title = doc.add_paragraph()
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    title.add_run().add_picture(str(png_path), width=Cm(1))
    run = title.add_run("Титул")
    run.font.size = Pt(16)
    doc.add_paragraph("Розділ", style="Heading 1")
    for text in ("Основний текст.", "Ще один абзац."):
        paragraph = doc.add_paragraph()
        paragraph.paragraph_format.first_line_indent = Cm(1.25)
        paragraph.add_run(text).font.size = Pt(14)
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)
    signature = doc.add_paragraph()
    signature.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    signature.add_run("звання\tПІДПИС").font.size = Pt(12)
    table = doc.add_table(rows=4, cols=3)
    table.style = "Table Grid"
    table.cell(0, 0).merge(table.cell(0, 2)).text = "АРКУШ"
    for index, header in enumerate(("Посада", "Звання", "Підпис")):
        table.cell(1, index).text = header
    table.cell(2, 0).text = "Посада 1"
    doc.save(path)
    return path
