import os
import re
from datetime import datetime

from docx import Document

from utils.logging_utils import print_red

# "ЖБД 08.05.2026.docx" - реальна конвенція іменування файлів журналу бойових
# дій (ЖБД), яку користувач фактично використовує (resources/Травень МП 2026) -
# ВІДМІННА і від "№NNN ЩОДЕННА/ЗАВДАННЯ ДД.ММ.РРРР.docx" (content/
# document_content_search.py::_DAILY_OR_TASK_FILENAME_RE), і від "Витяг з ЖБД
# для БР - ..." (formatting/docx_utils.py) - жодна з двох НЕ підходить для цих
# файлів. Лише .docx (легасі .doc - напр. титульна сторінка справи - свідомо
# ігнорується, не є щоденним документом ЖБД).
_LOG_WAR_FILENAME_RE = re.compile(r"^ЖБД\s+(\d{2}\.\d{2}\.\d{4})\.docx$", re.IGNORECASE)

# "5. Рішення командира військової частини (...) та бойові завдання,
# поставлені підпорядкованим частинам (підрозділам)." - секція, де сьогодні
# ставлять ЗАВТРАШНЄ завдання конкретній людині (переміщення/призначення).
_SECTION5_HEADING_RE = re.compile(r"^\s*5\.\s")
# "6. Відомості про виконання бойового (спеціального) завдання..." - секція, що
# підтверджує ФАКТИЧНЕ виконання завдань, поставлених РАНІШЕ (зокрема вчора в
# пункті 5).
_SECTION6_HEADING_RE = re.compile(r"^\s*6\.\s")
# Будь-який наступний нумерований заголовок ("5.1", "6.", "6.2." тощо) - межа,
# де закінчується вміст ПОПЕРЕДНЬОЇ секції/підсекції (не плутати з "5."/"6." -
# ті вимагають ПРОБІЛ одразу після крапки, тож "5.1" їх не зачіпає).
#
# РЕГРЕСІЯ (виявлено користувачем на реальному зразку 07.05.2026): "Хід
# виконання спланованих завдань" у реальних документах складається з
# ЧАСОВИХ заміток виду "20.00 07.05.2026 заступник командира... ПІБ...;" -
# наївний патерн \d+(?:\.\d+)*\.?\s ПОМИЛКОВО розпізнавав "20.00" (час) як
# нумерований заголовок і обривав секцію на ПЕРШОМУ ж такому запису (82
# символи замість реальних десятків тисяч) - усі подальші ПІБ губились.
# Виправлено ДВОМА уточненнями: (1) кожен числовий сегмент - НЕ БІЛЬШЕ 2 цифр
# (реальні заголовки - "5", "6.1", "9.2" тощо; "2026" з дати "07.05.2026" чи
# хвилини "00" з часу "20.00" не підходять під це обмеження в потрібному
# місці), і (2) ОДРАЗУ ПІСЛЯ номера має йти БУКВА (заголовок завжди
# продовжується словом - "6.1 Хід..."), а НЕ цифра (час/дата - "20.00
# 07.05.2026...", "07.05.2026 Відповідно..." - обидва відхиляються).
#
# РЕГРЕСІЯ 2 (виявлено користувачем на реальному зразку 01.07.2026, ДЯКОВИЧ
# Павло Богданович): текст пункту "5" рясніє позначеннями підрозділів БЕЗ
# крапки після числа - "1 бмп", "40 обрмн" тощо (а не лише датами/часом,
# уже виключеними вище) - ОДИНИЧНЕ число (без внутрішньої крапки, як у
# "9.2") з ОПЦІЙНОЮ крапкою в кінці (`\.?`) помилково визнавало "1 " перед
# "бмп" за заголовок "1." і обривало секцію "5" на 179 символах замість
# реальних кількох тисяч - увесь список ПІБ губився. Виправлено: для
# ОДИНИЧНОГО числа (без внутрішньої крапки) крапка ПІСЛЯ нього тепер
# ОБОВ'ЯЗКОВА (справжні заголовки верхнього рівня - завжди "5.", "6." з
# крапкою; голе число без крапки - позначення підрозділу/кількість, не
# заголовок); для багаторівневого номера ("9.2", "6.1" тощо) крапка в кінці
# лишається опційною, як і раніше (реальні зразки таких заголовків її не
# мають).
_NUMBERED_HEADING_RE = re.compile(r"^\s*(?:\d{1,2}\.|\d{1,2}(?:\.\d{1,2}){1,2}\.?)\s+(?=[^\d\s])")
# Підсекція всередині "6." - саме тут, за реальними зразками документів,
# з'являються ПІБ тих, чиї завдання, поставлені ВЧОРА (пункт 5), сьогодні
# підтверджено виконаними. НЕМАЄ як існуюча константа десь у коді (генератори
# ЖБД цього проєкту наразі взагалі не створюють такий підзаголовок) - текст
# підтверджено буквально в реальних зразках resources/Травень МП 2026.
_SECTION6_HID_SUBHEADING_RE = re.compile(r"^\s*Хід\s+виконання\s+спланованих\s+завдань\s*:?\s*$", re.IGNORECASE)


def scan_log_war_folder(folder):
    """Рекурсивно (os.walk) шукає файли "ЖБД ДД.ММ.РРРР.docx" у folder -
    {date: шлях}. Два файли з ОДНАКОВОЮ датою (малоймовірно, але можливо) -
    лишається ПЕРШИЙ (за впорядкованим обходом), з червоним попередженням
    (а не помилкою - перевірка продовжується з тим, що є)."""
    result = {}
    for dirpath, _dirnames, filenames in os.walk(folder):
        for filename in sorted(filenames):
            match = _LOG_WAR_FILENAME_RE.match(filename)
            if not match:
                continue
            date = datetime.strptime(match.group(1), "%d.%m.%Y")
            if date in result:
                print_red(f"Кілька файлів ЖБД за {match.group(1)} - лишаю {result[date]}, ігнорую {os.path.join(dirpath, filename)}.")
                continue
            result[date] = os.path.join(dirpath, filename)
    return result


def _read_log_war_paragraphs(file_path):
    """Реальні документи ЖБД (resources/Травень МП 2026) тримають УВЕСЬ
    багатосторінковий нумерований наратив (1.-9.4) ВСЕРЕДИНІ ОДНІЄЇ клітинки
    таблиці, а не як звичайні абзаци документа - extract_document_text
    (content/document_content_search.py) для цієї задачі не підходить: вона
    повертає ОДИН суцільний текст (абзаци+таблиці разом), без збереження
    порядку/меж окремих абзаців, потрібних тут для розрізання на секції.
    Повертає впорядкований список текстів абзаців - спершу з клітинок таблиць
    (якщо вони є - саме там реальний наратив), інакше - зі звичайних абзаців
    документа. Будь-яка помилка читання - червоне попередження і порожній
    список (пошук по решті файлів папки триває), як і extract_document_text."""
    try:
        doc = Document(file_path)
    except Exception as error:
        print_red(f"Не вдалось прочитати {file_path}: {error}")
        return []

    if doc.tables:
        return [
            paragraph.text
            for table in doc.tables
            for row in table.rows
            for cell in row.cells
            for paragraph in cell.paragraphs
        ]
    return [paragraph.text for paragraph in doc.paragraphs]


def _slice_after_heading(paragraphs, heading_re, start_index=0):
    """Шукає ПЕРШИЙ абзац (від start_index) що збігається з heading_re - і
    повертає (його індекс, текст УСІХ абзаців ПІСЛЯ нього аж до НАСТУПНОГО
    нумерованого заголовка _NUMBERED_HEADING_RE, чи кінця списку). Заголовок
    не знайдено - (None, ""). Порожній текст ПІСЛЯ знайденого заголовка (напр.
    "Хід виконання..." одразу ж перед "6.1") - ОЧІКУВАНИЙ, легітимний
    результат (реальний зразок - перехідний день без жодного підтвердження),
    а НЕ ознака помилки."""
    heading_index = next(
        (i for i in range(start_index, len(paragraphs)) if heading_re.match(paragraphs[i])),
        None,
    )
    if heading_index is None:
        return None, ""

    end_index = next(
        (i for i in range(heading_index + 1, len(paragraphs)) if _NUMBERED_HEADING_RE.match(paragraphs[i])),
        len(paragraphs),
    )
    return heading_index, "\n".join(paragraphs[heading_index + 1:end_index])


def extract_log_war_sections(file_path):
    """{"section5", "section6_hid"} - текст секції "5. Рішення командира..."
    (де СЬОГОДНІ ставлять завтрашнє завдання конкретній людині) і підсекції
    "Хід виконання спланованих завдань" усередині секції "6. Відомості про
    виконання..." (де СЬОГОДНІ підтверджують виконання ВЧОРАШНЬОГО завдання) -
    checker_accounting.report_log_war_checker звіряє ПІБ проти цих ДВОХ,
    ЗВУЖЕНИХ фрагментів (а не проти всього тексту документа), щоб не плутати,
    наприклад, екіпажі бойових вильотів (інша частина секції "6", інший формат
    згадки) з фактичним підтвердженням виконання спланованого завдання.
    Секцію(и) не знайдено - відповідне значення просто порожній рядок."""
    paragraphs = _read_log_war_paragraphs(file_path)

    _section5_index, section5_text = _slice_after_heading(paragraphs, _SECTION5_HEADING_RE)

    section6_hid_text = ""
    section6_index, _section6_text = _slice_after_heading(paragraphs, _SECTION6_HEADING_RE)
    if section6_index is not None:
        _hid_index, section6_hid_text = _slice_after_heading(paragraphs, _SECTION6_HID_SUBHEADING_RE, section6_index + 1)

    return {"section5": section5_text, "section6_hid": section6_hid_text}
