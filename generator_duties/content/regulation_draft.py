def battalion_names(data, suffixes):
    """→ (батальйон у називному, у родовому, військова частина в родовому).
    З data.json → unit, інакше з ланцюга вищого підрозділу штату."""
    unit = data.get("unit") or {}
    genitive = unit.get("BATTALION_GENITIVE") or next((s for s in suffixes if "батальйону" in s.lower()), "")
    genitive = clean_text(genitive) or "батальйону"
    nominative = re.sub(r"(?i)\bбатальйону\b", "батальйон", genitive, count=1)
    unit_genitive = unit.get("MILITARY_UNIT_GENITIVE") or next((s for s in suffixes if "частини" in s.lower()), "")
    return nominative, genitive, clean_text(unit_genitive)


def subunit_groups(slots):
    """Підрозділи верхнього рівня у порядку штату (колонка "підрозділ")."""
    groups = []
    for slot in slots:
        group = clean_text(slot.group)
        if group and compare_key(group) not in (compare_key(g) for g in groups):
            groups.append(group)
    return groups


def purpose(group):
    key = compare_key(group)
    return next((text for word, text in SUBUNIT_PURPOSES if word in key), DEFAULT_PURPOSE)


def leadership(positions):
    """Посади рівня батальйону (крім самого комбата) - керівний склад:
    "… батальйону" чи "… батальйону з <напрям>", але не "… батальйону взводу …"."""
    return [position.title for position in positions
            if (position.key.endswith("батальйону") or "батальйону з " in position.key)
            and position.key != "командир батальйону"]


def _capitalize(text):
    return text[:1].upper() + text[1:]


def build_regulation_draft(path, positions, slots, names):
    nominative, genitive, unit_genitive = names
    doc = Document()
    set_page(doc, top=Cm(1.0), bottom=Cm(1.5), left=Cm(2.5), right=Cm(1.5))
    set_base_font(doc)

    def center(text):
        add_paragraph_with_style(doc, text, bold=True, alignment=WD_ALIGN_PARAGRAPH.CENTER)

    def heading(text):
        add_paragraph_with_style(doc, text, bold=True, first_line_indent_cm=INDENT_CM)

    def text(value):
        add_paragraph_with_style(doc, value, first_line_indent_cm=INDENT_CM)

    def items(values):
        for value in values:
            text(f"– {value}")

    full_name = f"{nominative} {unit_genitive}".strip()
    center("ПОЛОЖЕННЯ")
    center(f"про {nominative}")
    if unit_genitive:
        center(unit_genitive)
    add_paragraph_with_style(doc, "")

    heading("1. Загальні положення")
    text(f"1.1. {_capitalize(full_name)} (далі – батальйон) є тактичним підрозділом і призначений для ведення "
         f"бойових дій самостійно або у складі військової частини.")
    text("1.2. Батальйон у своїй діяльності керується Конституцією України, законами України, статутами Збройних Сил "
         "України, наказами та директивами Міністра оборони України, Головнокомандувача Збройних Сил України, "
         "старших командирів (начальників) і цим Положенням.")
    text("1.3. Положення визначає призначення, склад, основні завдання, порядок керівництва, права, обов’язки та "
         "взаємодію батальйону.")

    heading("2. Основні завдання батальйону")
    items(TASKS)

    heading("3. Склад батальйону та призначення структурних підрозділів")
    groups = subunit_groups(slots)
    text("3.1. До організаційно-штатної структури батальйону входять:")
    items([f"{group};" for group in groups] or ["ЗАПОВНИТИ: перелік підрозділів;"])
    text("3.2. Призначення структурних підрозділів:")
    items([f"{group} – {purpose(group)};" for group in groups] or ["ЗАПОВНИТИ: призначення підрозділів;"])

    heading("4. Керівництво батальйону")
    superior = f"командиру {unit_genitive}" if unit_genitive else "старшому командиру"
    text(f"4.1. Батальйон очолює командир батальйону, який підпорядковується {superior} і є прямим начальником "
         f"усього особового складу батальйону.")
    text("4.2. Командир батальйону несе персональну відповідальність за бойову та мобілізаційну готовність батальйону, "
         "успішне виконання бойових завдань, бойову підготовку, виховання, військову дисципліну, морально-психологічний "
         "стан особового складу, збереження озброєння, техніки та майна.")
    text("4.3. До керівного складу батальйону також входять:")
    items([f"{title};" for title in leadership(positions)] + ["командири підрозділів батальйону."])

    heading("5. Права і обов’язки батальйону")
    text("Батальйон має право:")
    items(RIGHTS)
    text("Батальйон зобов’язаний:")
    items(OBLIGATIONS)

    heading("6. Взаємодія")
    text("6.1. Батальйон взаємодіє з підрозділами військової частини, сусідніми та підтримуючими підрозділами, "
         "органами управління та службами забезпечення.")
    text("6.2. Взаємодія організовується командиром батальйону (штабом) за завданнями, рубежами та часом відповідно "
         "до рішення старшого командира.")
    save_docx_safely(doc, path)
    return path


def ensure_regulation_draft(resources_dir, positions, slots, data, suffixes):
    """Створює чернетку, якщо в resources_dir немає жодного Положення*.docx.
    → шлях чернетки або None (Положення вже є)."""
    if find_resource(resources_dir, REGULATION_FILE_GLOB):
        return None
    path = os.path.join(resources_dir, os.path.basename(REGULATION_DRAFT_FILE_NAME))
    return build_regulation_draft(path, positions, slots, battalion_names(data, suffixes))
