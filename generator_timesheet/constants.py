# ("10_МЕД"), тож "ВЛК" перемагає "ВПСЗ". Правило діє, лише коли тут рівно
# один зі статусів пари; якщо обидва чи жоден - ручна перевірка. Статус,
# якого тут немає, вважається неоплачуваним (ВП, ВПСЗ, РВЗ тощо).
#
# "ППД" тут навмисно немає, хоча він оплачується (PAYMENT_STATUS_CONVERSIONS
# ["ППД"] = 10): "ВПСЗ" проти "ППД" - справжня суперечність фактів (не можна
# водночас бути у відпустці й у пункті постійної дислокації), а не
# продовження того самого медичного стану, як ВПСЗ -> ВЛК/ШП. Такі пари
# лишаються на ручну перевірку
# (test_apply_events_treats_vpsz_ppd_as_a_genuine_conflict).
