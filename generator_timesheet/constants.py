# Винятки - речення з ЦИМИ конкретними стійкими зворотами РОЗПІЗНАЮТЬСЯ як
# подія зміни статусу (підтверджено користувачем на реальних випадках з
# resources/report/*.docx, розділ "Поза межами"), незалежно від БАЗОВОГО
# статусу людини. Дата - опційна група ПЕРЕД самим зворотом ("05.08.2026 року
# вибув..."), запасний варіант - дата рапорту (як і для табличних подій),
# якщо перед зворотом дати нема (сама фраза може згадувати ІНШУ, не пов'язану
# дату ПІСЛЯ себе, напр. дату наказу ВЛК - тому шукаємо дату лише
# БЕЗПОСЕРЕДНЬО перед зворотом, не будь-яку в реченні). Дата, знайдена перед
# зворотом, і далі звіряється з колонками ОБЛІК.xlsx як завжди (apply_events)
# - друкарська помилка в самому реченні (напр. "06.07.2026" замість
# "06.08.2026") не застосовується мовчки, а лишається на ручну перевірку, як
# і для табличних подій із друкарськими помилками дат.
#
# "госпіталізован" - НЕЗАЛЕЖНО від БАЗОВОГО статусу людини: навіть якщо вона
# й так уже була "ШП" (просто перелягла в інший заклад) - результат все одно
# "ШП", тож застосування цієї події - безпечний "no-op", а не хибна зміна;
# підтверджено користувачем - такі речення НЕ повинні потрапляти в ручну
# перевірку лише через те, що статус фактично не змінився.
def _freeform_pattern(anchor):
    return re.compile(rf"(?:(?P<date>\d{{2}}\.\d{{2}}\.\d{{4}})\s*(?:року)?\s*)?{anchor}", re.IGNORECASE)


FREEFORM_STATUS_PATTERNS = (
    (_freeform_pattern(r"вибув\s+у\s+відпустку\s+за\s+станом\s+здоров['’]?я"), "ВПСЗ"),
    (_freeform_pattern(r"вибув\s+у\s+СЗЧ"), "СЗЧ"),
    # "госпіталізов?ан" (не буквальне "госпіталізован") - реальний випадок,
    # підтверджений користувачем: "03.09.2026 ГОСПІТАЛІЗОАНИЙ військовою
    # частиною ..." - друкарська помилка, пропущена буква "в" перед "аний"
    # ("госпіталізо" + "аний" замість "госпіталізо" + "ваний") - необов'язкове
    # "в?" покриває обидва написання, не змінюючи звичний випадок.
    (_freeform_pattern(r"госпіталізов?ан"), "ШП"),
    # "переводиться на наступний етап медичної евакуації" - той самий "ШП
    # незалежно від БАЗОВОГО статусу" принцип, що й "госпіталізован" вище,
    # лише іншими словами (ще в системі медичної евакуації, ще не на "волі").
    # "медичної" - НЕОБОВ'ЯЗКОВЕ слово (реальний випадок: "на наступний етап
    # евакуації", БЕЗ "медичної" - той самий сенс, коротшим формулюванням).
    # "наступн\w*\s+етап\w*" (а не буквальне "наступний етап") - реальний
    # випадок: "перебуває на НАСТУПНОМУ ЕТАП евакуації" (інший відмінок
    # "наступний" -> "наступному", і, вочевидь, описка "етап" замість
    # "етапі") - той самий сенс, стем-збіг покриває обидва написання.
    # "евакуації|госпіталізації" - реальний випадок, підтверджений
    # користувачем: "перебуває на наступному етап ГОСПІТАЛІЗАЦІЇ" (не
    # "евакуації") - той самий "ще лікується, ще не на волі" сенс, лише
    # іншим словом.
    (_freeform_pattern(r"наступн\w*\s+етап\w*\s+(?:медичної\s+)?(?:евакуації|госпіталізації)"), "ШП"),
    # "виписаний ... та на наступному етапі лікування до [заклад]" - реальний
    # випадок: виписка з ОДНОГО закладу, але ЗРАЗУ на наступний етап
    # ЛІКУВАННЯ (не медичної евакуації, як вище) в ІНШОМУ - той самий
    # "безпечний no-op" принцип, ШП незалежно від БАЗОВОГО статусу (людина й
    # далі лікується, лише в іншому закладі). ОБИДВА ключових слова
    # ("виписан" І "наступний етап лікування", у ЦЬОМУ порядку) - навмисно
    # ВУЖЧЕ за просто "наступний етап лікування" саме по собі (яке могло б
    # трапитись і поза контекстом виписки).
    (_freeform_pattern(r"виписан\w*.*?наступн\w*\s+етап\w*\s+лікуванн\w*"), "ШП"),
    # "переведений з [відділення] ... до [відділення]" - переведення МІЖ
    # відділеннями В МЕЖАХ лікування (той самий заклад чи інший, не важливо),
    # а НЕ переведення до іншого підрозділу/частини (те "переведений" - лише
    # в заголовках таблиць, STATUS_HEADING_RULES, статус "ПРВД") - людина й
    # далі лікується, тож статус лишається "ШП" НЕЗАЛЕЖНО від БАЗОВОГО (той
    # самий "безпечний no-op" принцип, що й "госпіталізован" вище). Ключове
    # слово "відділення" з ОБОХ боків ("з ... відділення" і "до ... відділення")
    # відрізняє це саме від переведення до іншого підрозділу.
    (_freeform_pattern(r"переведен\w*\s+з\s+.+?відділенн\w*.*?до\s+.+?відділенн\w*"), "ШП"),
    # "переведений в інше відділення [заклад]" - реальний випадок,
    # підтверджений користувачем: ТЕ САМЕ переведення МІЖ відділеннями в
    # межах лікування, що й "з ... відділення ... до ... відділення" вище,
    # лише КОРОТШИМ формулюванням - називає ЛИШЕ відділення ПРИЗНАЧЕННЯ (без
    # "з", без явного відділення-джерела) - ключове слово "відділення"
    # (а не "підрозділ"/"частина") відрізняє це від переведення до ІНШОГО
    # підрозділу/частини (STATUS_HEADING_RULES, статус "ПРВД"). Той самий
    # "безпечний no-op" принцип - ШП незалежно від БАЗОВОГО статусу.
    (_freeform_pattern(r"переведен\w*\s+[ву]\s+інш\w*\s+відділенн\w*"), "ШП"),
    # "продовжено відрядження ... від ДАТА" - відрядження й далі триває
    # (статус лишається "ВД" незалежно від БАЗОВОГО - той самий "безпечний
    # no-op" принцип). Дата - ПІСЛЯ звороту ("від ДАТА" наприкінці речення),
    # а не перед ним, як у _freeform_pattern - тому окремий, "сирий" regex
    # (не через _freeform_pattern) із власною named-групою "date" де завгодно
    # в межах patternу; _freeform_event нижче лише читає match.group("date"),
    # де саме вона в regex - неважливо.
    (re.compile(r"продовжен\w*\s+відрядженн\w*.*?від\s+(?P<date>\d{2}\.\d{2}\.\d{4})", re.IGNORECASE), "ВД"),
    # "від ДАТА проходить реабілітацію" - людина й далі лікується (просто вже
    # на етапі реабілітації, а не в самій лікарні) - статус лишається "ШП"
    # незалежно від БАЗОВОГО, той самий принцип, що й "госпіталізован"/
    # "переведений... відділення" вище. "від"/"з" (а не лише "від") -
    # реальний випадок, підтверджений користувачем: "ТА З ДАТА проходить
    # реабілітацію" - інший прийменник, той самий сенс.
    (re.compile(r"(?:від|з)\s+(?P<date>\d{2}\.\d{2}\.\d{4})\s+проходить\s+реабілітаці\w*", re.IGNORECASE), "ШП"),
    # "ДАТА почав проходження військово-лікарської комісії" АБО "ДАТА пройшов
    # військово лікарську комісію" - ОБИДВІ - реальні випадки, підтверджені
    # користувачем: людина ЩОЙНО РОЗПОЧАЛА чи вже ПРОЙШЛА комісію (той самий
    # сенс, що й _VLK_IN_PROGRESS_RE у daily_report_reader.py - "проходить
    # ВЛК"/"приступив до проходження ВЛК" - але ЦІ речення НЕ супроводжуються
    # жодною згадкою потреби відпустки, тож складніший
    # _discharge_vlk_leave_events/_vlk_in_progress_anchor_event (обидва
    # вимагають ДОДАТКОВИЙ контекст виписки/відпустки) на них узагалі не
    # спрацював би - просте одноподієве правило тут якраз до місця).
    # "почав" вимагає слова "проходженн\w*" МІЖ собою і "військово..."
    # (структура "почав проходження ВЛК"), а "пройшов" - НІ (структура
    # "пройшов ВЛК", без проміжного іменника) - дві РІЗНІ граматичні форми
    # ОДНІЄЇ дії. "військово[\s-]лікарськ\w*" (а не лише через дефіс) -
    # реальний випадок: "пройшов ВІЙСЬКОВО ЛІКАРСЬКУ комісію" - БЕЗ дефіса,
    # двома окремими словами (одруківка чи стиль конкретного рапорту).
    (_freeform_pattern(r"(?:почав\w*\s+проходженн\w*|пройшов\w*)\s+військово[\s-]лікарськ\w*\s+комісі\w*"), "ВЛК"),
    # "з ДАТА відпустка за сімейними обставинами" - реальний випадок,
    # підтверджений користувачем: "ВПС" ("Відпустка за сімейними
    # обставинами" - ОКРЕМИЙ, вже підтримуваний статус, відмінний від "ВП"
    # (звичайна відпустка) і "ВПСЗ"/"ВПЗС" (за станом здоров'я) - STATUS_
    # DESCRIPTIONS/STATUS_COLORS/PAYMENT_STATUS_OVERRIDES["ВП"]["ВПС"] вище
    # вже його знають, лише жодне freeform-речення досі на нього не
    # виводило). На відміну від інших зворотів у цій таблиці, тут НЕМАЄ
    # дієслова "вибув"/"перебуває" - саме речення лише НАЗИВАЄ статус ("з
    # ДАТА [статус]"), той самий "дата ПЕРЕД зворотом" принцип.
    (_freeform_pattern(r"відпустк\w*\s+за\s+сімейними\s+обставинами"), "ВПС"),
    # "ртгр" - за прямою вказівкою користувача, НА МАЙБУТНЄ (запобіжник):
    # STATUS_HEADING_RULES["ртгр"] вище вже ловить це у ЗАГОЛОВКУ таблиці
    # ("В РТГР:"), але той самий факт (вибуття до РТГр, можливо, з
    # конкретною назвою угрупування після - напр. "вибув до ртгр [назва]")
    # МОЖЕ колись з'явитись і ВІЛЬНИМ ТЕКСТОМ розділу "Поза межами..." замість
    # таблиці - той самий "простий підрядок замість жорсткого граматичного
    # звороту" принцип, що й у заголовку (абревіатура "ртгр" достатньо
    # самобутня, щоб не плутатись із чимось іншим у вільному тексті).
    # НАЗВУ угрупування (якщо є) навмисно НЕ включено як окреме слово в
    # regex - це реальний позивний/номер конкретного підрозділу, тож не
    # хардкодиться в трекованому коді (той самий принцип, що й SIGNATORY_
    # UNIT_NAMES/resources/data.json) - весь "хвіст" після "ртгр" просто
    # не впливає на збіг.
    (_freeform_pattern(r"ртгр"), "РТГр"),
)

# Коли для однієї людини на ОДНУ дату в рамках одного рапорту знайдено ДВА
# РІЗНІ статуси - зазвичай це справжня суперечність (ручна перевірка). Але
# для деяких пар один статус ЗАВІДОМО специфічніший за інший (той самий факт
# відсутності, лише уточнена причина) - тоді це НЕ суперечність: специфічніший
# статус застосовується напряму, без запису на ручну перевірку, незалежно від
# порядку появи в рапорті. Підтверджено користувачем на реальному випадку:
# "ВП" (відпустка) і "ВПСЗ" (відпустка за станом здоров'я) - ВПСЗ це той самий
# факт відпустки з уточненою причиною, тож завжди перемагає.
STATUS_CONFLICT_OVERRIDES = {
    frozenset({"ВП", "ВПСЗ"}): "ВПСЗ",
    # Реальний випадок, підтверджений користувачем: перший рапорт (сам факт
    # "потребує відпустки для лікування після поранення") дає "ВПБП", а
    # ПІЗНІШИЙ рапорт ОКРЕМИМ реченням підтверджує ТОЙ САМИЙ день як "вибув
    # у відпустку ЗА СТАНОМ ЗДОРОВ'Я" (ВПСЗ, FREEFORM_STATUS_PATTERNS) - той
    # самий факт відпустки, лише ПІЗНІШЕ підтверджений ІНШИМ формулюванням
    # причини (той самий принцип, що й "ВП"/"ВПСЗ" вище) - "ВПСЗ" перемагає
    # (запобіжник - content/daily_report_reader.py::_discharge_vlk_leave_events
    # УЖЕ й сам НЕ обирає "ВПБП", коли те САМЕ речення згадує ще й "за станом
    # здоров'я", але ЦЕЙ конфлікт може виникнути МІЖ ДВОМА РІЗНИМИ рапортами,
    # де кожен бачить лише СВОЄ речення).
    frozenset({"ВПБП", "ВПСЗ"}): "ВПСЗ",
}

