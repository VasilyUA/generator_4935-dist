def _date_name_pairs(key):
    """[{"date": "дд.мм.рррр", "name": "ПІБ"}, ...] з resources/data.json ->
    кортежі (date, name). ПІБ лишається як є - нормалізація в generators/, бо
    constants.py не імпортує content/. Запис, який не вдається прочитати (не
    об'єкт, немає ПІБ, дата не у форматі дд.мм.рррр, напр. "06.092026"), - це
    помилка одразу: інакше виняток для одного запису тихо не спрацював би, і
    запис лишився б у файлі для ручної перевірки без жодного пояснення."""
    raw = _DATA.get(key, [])
    if not isinstance(raw, list):
        raise ValueError(f"resources/data.json: \"{key}\" має бути списком об'єктів {{\"date\", \"name\"}}.")
    pairs = []
    for entry in raw:
        if not isinstance(entry, dict) or not isinstance(entry.get("name"), str) or not entry["name"].strip():
            raise ValueError(f"resources/data.json: у \"{key}\" запис {entry!r} - очікується {{\"date\": \"дд.мм.рррр\", \"name\": \"ПІБ\"}}.")
        date_text = entry.get("date")
        if not isinstance(date_text, str):
            raise ValueError(f"resources/data.json: у \"{key}\" дата {date_text!r} не у форматі дд.мм.рррр.")
        try:
            day = datetime.strptime(date_text, "%d.%m.%Y").date()
        except ValueError:
            raise ValueError(f"resources/data.json: у \"{key}\" дата {date_text!r} не у форматі дд.мм.рррр.") from None
        pairs.append((day, entry["name"]))
    return tuple(pairs)


