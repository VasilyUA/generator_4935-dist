# Винятки: речення з цими сталими зворотами впізнаються як зміна статусу,
# хоч би який був базовий статус людини (підтверджено на реальних
# resources/report/*.docx, розділ "Поза межами"). Дата - необов'язкова група
# одразу перед зворотом ("05.08.2026 року вибув..."), а якщо її немає - дата
# рапорту, як і для табличних подій. Шукається саме дата перед зворотом, а не
# будь-яка в реченні: після звороту часто стоїть інша дата (напр. наказу
# ВЛК). Знайдена дата, як завжди, звіряється з колонками ОБЛІК.xlsx
# (apply_events), тож описка в реченні ("06.07.2026" замість "06.08.2026")
# не застосовується мовчки, а йде на ручну перевірку.
#
# "госпіталізован" дає "ШП" незалежно від базового статусу. Якщо людина вже
# була "ШП" (просто перелягла в інший заклад), застосування нічого не
# змінює, і це безпечно. Такі речення не мають іти на ручну перевірку лише
# тому, що статус фактично не змінився (підтвердив користувач).
def _freeform_pattern(anchor):
    return re.compile(rf"(?:(?P<date>\d{{2}}\.\d{{2}}\.\d{{4}})\s*(?:року)?\s*)?{anchor}", re.IGNORECASE)


FREEFORM_STATUS_PATTERNS = (
    (_freeform_pattern(r"вибув\s+у\s+відпустку\s+за\s+станом\s+здоров['’]?я"), "ВПСЗ"),
    (_freeform_pattern(r"вибув\s+у\s+СЗЧ"), "СЗЧ"),
    # "госпіталізов?ан": у реальному рапорті було "ГОСПІТАЛІЗОАНИЙ" (пропущена
    # "в"), тож "в?" покриває обидва написання.
    (_freeform_pattern(r"госпіталізов?ан"), "ШП"),
    # "переводиться на наступний етап медичної евакуації" - як і
    # "госпіталізован", "ШП" незалежно від базового статусу: людина ще в
    # системі медичної евакуації. Слово "медичної" необов'язкове ("на наступний
    # етап евакуації"). "наступн\w*\s+етап\w*" покриває інші відмінки й описки
    # ("перебуває на наступному етап евакуації"). "евакуації|госпіталізації" -
    # бо буває й "на наступному етап госпіталізації" з тим самим сенсом.
    (_freeform_pattern(r"наступн\w*\s+етап\w*\s+(?:медичної\s+)?(?:евакуації|госпіталізації)"), "ШП"),
    # "виписаний ... та на наступному етапі лікування до [заклад]" - виписка з
    # одного закладу й одразу наступний етап лікування в іншому, тож "ШП"
    # незалежно від базового статусу. Потрібні обидва ключові слова в цьому
    # порядку ("виписан", потім "наступний етап лікування"): саме по собі
    # "наступний етап лікування" буває й поза контекстом виписки.
    (_freeform_pattern(r"виписан\w*.*?наступн\w*\s+етап\w*\s+лікуванн\w*"), "ШП"),
    # "виписаний ... направляється для подальшого лікування в [заклад]" - той
    # самий сенс іншими словами: виписка з одного закладу й одразу подальше
    # лікування в іншому, "ШП" незалежно від базового статусу.
    (_freeform_pattern(r"виписан\w*.*?направля\w*\s+для\s+подальшого\s+лікуванн\w*"), "ШП"),
    # "переведений з [відділення] ... до [відділення]" - переведення між
    # відділеннями під час лікування, а не до іншого підрозділу чи частини
    # (таке "переведений" буває лише в заголовках таблиць, STATUS_HEADING_RULES,
    # статуси "ПРВДБ"/"ПРВДВЧ"). Людина далі лікується, тож "ШП". Слово
    # "відділення" з обох боків і відрізняє це від переведення до підрозділу.
    (_freeform_pattern(r"переведен\w*\s+з\s+.+?відділенн\w*.*?до\s+.+?відділенн\w*"), "ШП"),
    # "переведений в інше відділення [заклад]" - те саме переведення між
    # відділеннями, лише коротше: названо тільки відділення, куди переведено.
    # Слово "відділення" (а не "підрозділ"/"частина") відрізняє це від
    # переведення до іншого підрозділу. "ШП" незалежно від базового статусу.
    (_freeform_pattern(r"переведен\w*\s+[ву]\s+інш\w*\s+відділенн\w*"), "ШП"),
    # "продовжено відрядження ... від ДАТА" - відрядження триває, тож "ВД"
    # незалежно від базового статусу. Дата тут після звороту ("від ДАТА"
    # наприкінці речення), а не перед ним, тому окремий regex без
    # _freeform_pattern, з власною групою "date" - _freeform_event читає
    # match.group("date"), де б вона не стояла.
    (re.compile(r"продовжен\w*\s+відрядженн\w*.*?від\s+(?P<date>\d{2}\.\d{2}\.\d{4})", re.IGNORECASE), "ВД"),
    # "від ДАТА проходить реабілітацію" - людина далі лікується, лише вже на
    # реабілітації, тож "ШП" незалежно від базового статусу. "від" чи "з" -
    # буває й "та з ДАТА проходить реабілітацію".
    (re.compile(r"(?:від|з)\s+(?P<date>\d{2}\.\d{2}\.\d{4})\s+проходить\s+реабілітаці\w*", re.IGNORECASE), "ШП"),
    # "ДАТА почав проходження військово-лікарської комісії" або "ДАТА пройшов
    # військово лікарську комісію" - людина щойно почала чи вже пройшла комісію
    # (той самий сенс, що й _VLK_IN_PROGRESS_RE у daily_report_reader.py). Але
    # тут немає згадки про відпустку, тож складніші
    # _discharge_vlk_leave_events/_vlk_in_progress_anchor_event (обидва чекають
    # контексту виписки чи відпустки) не спрацюють - досить простого правила.
    # Після "почав" має стояти "проходженн\w*" ("почав проходження ВЛК"), а після
    # "пройшов" - ні ("пройшов ВЛК"): це дві граматичні форми однієї дії.
    # "військово[\s-]лікарськ\w*", бо пишуть і без дефіса ("військово лікарську").
    #
    # "закінч\w*"/"заверш\w*" ("ДАТА закінчив/завершив [проходження]
    # військово-лікарської комісії") - теж "ВЛК" на дату завершення (рішення
    # користувача); "проходженн\w*" тут необов'язкове. Але лише коли в решті
    # речення немає "відпуст..." і "самовільн..." (негативний lookahead у кінці
    # гілки): "закінчив ВЛК ..., потребує відпустки", "..., вибув у відпустку"
    # чи "... самовільно залишив частину" - це складніші сценарії
    # (_discharge_vlk_leave_events, _dated_treatment_leave_event,
    # _discharge_then_awol_event), а _freeform_event перевіряється першим і без
    # обмеження "з'їв" би їх, лишивши "ВЛК" без парної відпустки чи СЗЧ. Гілка
    # "почав.../пройшов..." такого обмеження не має (поруч може бути й "під час
    # відпустки за станом здоров'я").
    # "(?(date)...|(?!))": гілка "закінч/заверш" спрацьовує, лише коли дата
    # стоїть впритул до звороту (група date з _freeform_pattern збіглась). Інакше
    # подія лягла б на дату рапорту, а не на день завершення, тож такий випадок
    # іде на ручну перевірку.
    (_freeform_pattern(
        r"(?:(?:почав\w*\s+проход\w*|пройшов\w*)\s+військово[\s-]лікарськ\w*\s+комісі\w*"
        r"|(?(date)(?:закінч|заверш)\w*(?:\s+проход\w*)?\s+військово[\s-]лікарськ\w*\s+комісі\w*"
        r"(?!(?s:.*)(?:відпуст|самовільн))|(?!)))"
    ), "ВЛК"),
    # "з ДАТА відпустка за сімейними обставинами" - "ВПС", окремий статус
    # (відмінний від "ВП" і від "ВПСЗ"/"ВПЗС"), який STATUS_DESCRIPTIONS,
    # STATUS_COLORS і PAYMENT_STATUS_OVERRIDES["ВП"]["ВПС"] уже знають; бракувало
    # лише речення, що його дає. Дієслова "вибув"/"перебуває" тут немає: речення
    # лише називає статус ("з ДАТА [статус]"), дата - так само перед зворотом.
    (_freeform_pattern(r"відпустк\w*\s+за\s+сімейними\s+обставинами"), "ВПС"),
    # "ртгр" - запобіжник на майбутнє (рішення користувача).
    # STATUS_HEADING_RULES["ртгр"] уже ловить це в заголовку таблиці ("В
    # РТГР:"), але той самий факт (вибуття до РТГр, можливо з назвою
    # угруповання - "вибув до ртгр [назва]") колись може з'явитися й вільним
    # текстом у "Поза межами...". Абревіатура достатньо своєрідна, тож досить
    # простого підрядка. Назви угруповання в шаблоні навмисно немає: це
    # справжній позивний чи номер підрозділу, і в коді його бути не може (як і
    # SIGNATORY_UNIT_NAMES) - решта тексту після "ртгр" на збіг не впливає.
    # "з РТГр" - повернення, а не вибуття: такого статусу не дає, речення йде
    # на ручну перевірку.
    (_freeform_pattern(r"(?<!\bз\s)(?<!\bіз\s)ртгр"), "РТГр"),
)

# Два різні статуси для однієї людини на ту саму дату - зазвичай справжня
# суперечність (ручна перевірка). Але в деяких парах один статус точніший за
# інший (той самий факт відсутності з уточненою причиною) - тоді точніший
# застосовується одразу, без ручної перевірки й незалежно від порядку в
# рапорті. Приклад, підтверджений користувачем: "ВП" і "ВПСЗ" - ВПСЗ це та
# сама відпустка з причиною, тож вона завжди перемагає.
#
# {ППД, ВЛК} -> ППД - так само, як {РВЗ, ВЛК} -> РВЗ (рішення користувача):
# рядок таблиці "З проходження ВЛК:" з "Куди прибув" - "до пункту постійної
# дислокації" (_table_events ставить "ППД") - це те саме повернення з
# комісії, лише в ППД. Реальний випадок: рапорт одного дня - "ДАТА закінчив
# проходження ВЛК" (ВЛК), наступного - "прибув до ППД з ВЛК" з тією самою
# датою. Без цієї пари правило "хто оплачується" віддавало день ВЛК і далі
# переносило ВЛК замість ППД.
STATUS_CONFLICT_OVERRIDES = {
    frozenset({"ВП", "ВПСЗ"}): "ВПСЗ",
    frozenset({DEFAULT_STATUS, "ВЛК"}): DEFAULT_STATUS,
    frozenset({"ППД", "ВЛК"}): "ППД",
}

# Автоматичне розв'язання суперечності "два різні статуси на одну дату"
# (apply_events), коли готової пари в STATUS_CONFLICT_OVERRIDES немає (та
# таблиця - підтверджені вручну винятки на кшталт {РВЗ,ВЛК}->РВЗ, де "хто
# оплачується" дав би неправильну відповідь; вона перевіряється першою).
# Принцип (рішення користувача): статус, за який належить виплата сам по собі
# (категорія з PAYMENT_STATUS_CONVERSIONS чи PAYMENT_STATUS_OVERRIDES[статус]
# [статус], без підтвердження information_unit), перемагає статус, за який
# виплати немає (напр. "ВПСЗ" - відпустка за станом здоров'я не оплачується).
