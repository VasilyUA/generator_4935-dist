        raise ValueError(
            "constants.py: PAYMENT_CATEGORY_100_MAX_DAYS - потрібні всі 12 місяців назвою з малої літери "
            f"({', '.join(months)}) і ціле число днів від 0 до 31; перевірте: {wrong}."
        )


