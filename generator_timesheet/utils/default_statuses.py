def _by_text(mapping):
    return {str(key): value for key, value in mapping.items()}


def default_status_data():
    """Стандартні статуси у формі, яку дає project_settings.read_settings:
    {"STATUSES": [...], "PAYMENT_STATUS_OVERRIDES": [...], "PAYMENT_STATUS_PRIORITY": [...]}."""
    meanings = {**_EXTRA_MEANINGS, **STATUS_MEANINGS}
    colors, conversions, fallbacks = _by_text(STATUS_COLORS), _by_text(PAYMENT_STATUS_CONVERSIONS), _by_text(PAYMENT_STATUS_FALLBACKS)
    statuses = [
        {
            "status": status, "code": status, "meaning": meanings.get(status, ""), "color": colors.get(status),
            "payment": conversions.get(status), "fallback": fallbacks.get(status),
        }
        for status in _status_order()
    ]
    overrides = [
        {"status": status, "unit_status": unit_status, "value": value}
        for status, override_map in PAYMENT_STATUS_OVERRIDES.items()
        for unit_status, value in override_map.items()
    ]
    priority = [
        {"first": first, "second": second, "winner": winner}
        for (first, second), winner in (
            (sorted(pair, key=lambda status: status != winner), winner) for pair, winner in PAYMENT_STATUS_PRIORITY.items()
        )
    ]
    return {
        "STATUSES": statuses, "PAYMENT_STATUS_OVERRIDES": overrides, "PAYMENT_STATUS_PRIORITY": priority,
        **default_rule_data(),
    }


